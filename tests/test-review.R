run_roundtrip <- function() {
  file <- tempfile(fileext = ".sqlite")
  summary_file <- tempfile(fileext = ".sqlite")
  on.exit(unlink(c(file, summary_file)), add = TRUE)
  path <- grep("patab", cand$table_catalog, value = TRUE)
  tables <- nmreview:::nm_inspector_sections(cand, path)
  project$models[[2L]]$stored_tables[[path]] <- tables
  project$view <- list(inspector = list(ids = "20", filters = list(list(column = "TIME", operator = "ge", value = 2)),
    table = path, x = "WT", y = "ETA1"))
  save_archive(project, file)
  reopened <- load_archive(file)
  stopifnot(reopened$schema_version == 2L, is.null(reopened$models[[2L]]$live_root),
    identical(nmreview:::nm_inspector_sections(reopened$models[[2L]], path), tables),
    identical(reopened$view, project$view), identical(reopened$models[[2L]]$review$shrinkage, s))
  save_archive(project, summary_file, FALSE)
  summary <- load_archive(summary_file)
  stopifnot(is.null(summary$models[[2L]]$stored_tables), is.null(summary$view$inspector$ids), is.null(summary$view$inspector$filters),
    identical(summary$models[[2L]]$review$shrinkage, s), identical(nmreview:::nm_model_aic(summary$models[[2L]])$value, b$value))
}
run_roundtrip()

