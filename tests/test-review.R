# An identified table can be selected explicitly. An unselected multistage
# problem has no preferred final estimate.
local({
  folder <- tempfile("nmreview-stages-")
  dir.create(folder)
  on.exit(unlink(list.files(folder, full.names = TRUE)), add = TRUE)
  on.exit(unlink(folder), add = TRUE, after = TRUE)
  put <- function(name, lines) writeLines(lines, file.path(folder, name))
  method <- "First Order Conditional Estimation with Interaction"
  put("multi.mod", c("$PROBLEM two fits", "$THETA 1", "$EST METHOD=1 INTERACTION", "$EST METHOD=1 INTERACTION"))
  put("multi.ext", c(
    paste0("TABLE NO. 3: ", method, ": Problem=1 Subproblem=0"),
    "ITERATION THETA1 OBJ", "-1000000000 2 100", "-1000000006 0 0",
    paste0("TABLE NO. 5: ", method, ": Problem=1 Subproblem=0"),
    "ITERATION THETA1 OBJ", "-1000000000 3 96", "-1000000006 0 0"))
  put("multi.lst", c("PROBLEM NO.: 1", "#TBLN: 3", "#TERM:", "0MINIMIZATION SUCCESSFUL",
    "ETASHRINKSD(%) 11", "#TERE:", "#TBLN: 5", "#TERM:", "0MINIMIZATION SUCCESSFUL",
    "ETASHRINKSD(%) 31", "#TERE:"))
  m <- import_project(folder)$models[[1L]]
  first <- nmreview:::nm_select_stage(m, "3")
  second <- nmreview:::nm_select_stage(m, "5")
  stopifnot(is.na(m$ofv), first$ofv == 100, second$ofv == 96,
    first$review$shrinkage$Value == 11, second$review$shrinkage$Value == 31,
    first$review$shrinkage$Line == 5L, second$review$shrinkage$Line == 10L)
})
